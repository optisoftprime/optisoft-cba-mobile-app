/* global __dirname -- a Node build script, not app code */
/**
 * Switch the app to a client:   npm run brand:use <client>
 *
 * Every client CBA-Mobile is sold to lives in clients/<client>/:
 *   client.json   name, store ids, org key, colours, Expo project (see BRANDING.md)
 *   assets/       icon.png, adaptive-icon.png, adaptive-icon-monochrome.png,
 *                 favicon.png, logo.png, logo-dark.png
 *   source/       the client's original artwork (kept so icons can be regenerated)
 *
 * The app is always built from brand/ — this copies the chosen client into it,
 * puts that client's signing config in place (credentials/<client>/, never
 * committed), then runs the brand check so a broken client fails here rather
 * than in a store review.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const id = process.argv[2];
const clientsDir = path.join(ROOT, 'clients');
const available = fs.existsSync(clientsDir)
  ? fs.readdirSync(clientsDir).filter((d) => fs.existsSync(path.join(clientsDir, d, 'client.json')))
  : [];

if (!id || !available.includes(id)) {
  console.error(
    `Usage: npm run brand:use <client>\nAvailable clients: ${available.join(', ') || '(none)'}`
  );
  process.exit(1);
}

const from = path.join(clientsDir, id);
const brand = path.join(ROOT, 'brand');

// brand/ is replaced wholesale, so nothing of the previous client survives.
fs.rmSync(brand, { recursive: true, force: true });
fs.mkdirSync(path.join(brand, 'assets'), { recursive: true });
fs.copyFileSync(path.join(from, 'client.json'), path.join(brand, 'client.json'));
for (const file of fs.readdirSync(path.join(from, 'assets'))) {
  fs.copyFileSync(path.join(from, 'assets', file), path.join(brand, 'assets', file));
}
fs.writeFileSync(
  path.join(brand, 'README.md'),
  `# Active client: ${id}\n\nGenerated by \`npm run brand:use ${id}\` — do not edit here.\n` +
    `Edit clients/${id}/ and run the command again. See BRANDING.md.\n`
);
console.log(`brand/ now holds client "${id}".`);

// Signing: EAS reads ./credentials.json. Each client has its own keystore.
const creds = path.join(ROOT, 'credentials', id, 'credentials.json');
if (fs.existsSync(creds)) {
  fs.copyFileSync(creds, path.join(ROOT, 'credentials.json'));
  console.log(`credentials.json -> credentials/${id}/ (signing key for "${id}").`);
} else {
  fs.rmSync(path.join(ROOT, 'credentials.json'), { force: true });
  console.log(
    `No credentials/${id}/credentials.json — the first build will need a signing key ` +
      `(see BRANDING.md, "Signing key").`
  );
}

execFileSync(process.execPath, [path.join(__dirname, 'check-brand.js')], { stdio: 'inherit' });

console.log(
  '\nNext: npx expo start -c   (or for a native/dev build: npx expo prebuild --clean)\n' +
    'Build: eas build --platform android --profile preview'
);
